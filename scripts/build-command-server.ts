// Compiles the sandbox command server for the machines GKE runs sandboxes on and writes it into
// src/command-server-binary.ts, which the package ships. Run it after changing
// command-server/command-server.c; a test fails while the two disagree.
//
//   bun scripts/build-command-server.ts      (needs `zig` 0.15 on the PATH)
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const source = join(import.meta.dir, '../command-server/command-server.c');
const directory = await mkdtemp(join(tmpdir(), 'command-server-'));
// Named as `uname -m` prints them, which is how a pod picks its own.
const machines = ['x86_64', 'aarch64'];
const binaries: Record<string, string> = {};
for (const machine of machines) {
  const output = join(directory, machine);
  const compiled = Bun.spawnSync(
    [
      'zig',
      'cc',
      '-target',
      `${machine}-linux-musl`,
      '-static',
      '-Os',
      '-s',
      '-Wall',
      '-Wextra',
      '-Werror',
      '-o',
      output,
      source,
    ],
    { stdout: 'inherit', stderr: 'inherit' },
  );
  if (compiled.exitCode !== 0) process.exit(compiled.exitCode ?? 1);
  binaries[machine] = (await readFile(output)).toString('base64');
}
await rm(directory, { recursive: true });
const sha256 = (value: string | Buffer) => createHash('sha256').update(value).digest('hex');
await writeFile(
  join(import.meta.dir, '../src/command-server-binary.ts'),
  `// Generated by scripts/build-command-server.ts from command-server/command-server.c. Do not edit.
export const COMMAND_SERVER = {
  sourceSha256: '${sha256(await readFile(source))}',
  sha256: '${sha256(machines.map((machine) => binaries[machine]).join('\n'))}',
  /** Static Linux programs in base64, by what \`uname -m\` prints. */
  binaries: {
${machines.map((machine) => `    ${machine}:\n      '${binaries[machine]}',`).join('\n')}
  },
};
`,
);
